"""The render layer: every table must carry its own provenance, and the HTML must be standalone."""

from __future__ import annotations

from pathlib import Path

import pytest

from carpet_scan.model import (
    DepthRow,
    FolderRow,
    PrivateRow,
    ScanConfig,
    SurfaceRow,
    ToolVersions,
    VultureFinding,
)
from carpet_scan.report import render_html, render_markdown

CONFIG = ScanConfig(
    src=Path("src"),
    tests=Path("tests"),
    package="pkg",
    top=12,
    warn_depth=3,
    modules=42,
    versions=ToolVersions(
        pyan3="1.2.0", vulture="2.16", radon="6.0.1", grimp="3.15", ruff="0.15.12"
    ),
    surface_skip=("scripts",),
    skipped=1,
    ignore_decorators="@app.command",
)
SURFACE = [
    SurfaceRow(
        module="src.pkg.api",
        publics=5,
        home_only=["only_home"],
        unused=["is_dead"],
        modifiers=[("rule", 4)],
        max_complexity=9,
        maintainability=71.25,
    )
]
DEPTH = [DepthRow(module="src.pkg.api", depth=4, chain=["a", "b", "c", "d", "e"], trivial=3)]
FOLDERS = [FolderRow(folder="pkg.rules", modules=6, edges=10, depth=4, chain=["loader", "schema"])]
PRIVATE = [PrivateRow(module="tests.test_api", attribute=4, imported=2, names=["_helper"])]
DEAD = [
    VultureFinding(
        path=Path("src/pkg/api.py"), lineno=41, kind="function", name="is_dead", confidence=60
    )
]


@pytest.fixture
def markdown() -> str:
    return render_markdown(SURFACE, DEPTH, FOLDERS, DEAD, PRIVATE, CONFIG)


def test_every_table_states_the_command_that_produced_it(markdown: str) -> None:
    """A reader checking one number must not have to scroll to the Method section to find out
    which tool and which options produced it."""
    assert markdown.count("*Generated by:*") == 5, (
        "surface, private access, call depth, folder depth, dead code"
    )
    # The tables built from more than one tool name every tool they used.
    surface, _, rest = markdown.partition("## Private names used across module boundaries")
    assert "pyan3" in surface and "vulture" in surface and "radon" in surface
    private, _, rest = rest.partition("## Intra-module call depth")
    assert "SLF001,PLC2701" in private and "--preview" in private
    depth, _, folders = rest.partition("## Intra-folder import depth")
    assert "pyan3" in depth and "radon cc" in depth
    assert "grimp.build_graph('pkg')" in folders


def test_every_table_defines_its_own_columns(markdown: str) -> None:
    assert markdown.count("| column | meaning |") == 5
    for column in ("worst cc", "mi", "cc1", "deepest chain", "confidence"):
        assert f"| {column} |" in markdown, f"{column} is used in a table but never defined"


def test_headings_are_descriptive_and_the_numbers_are_cross_references(markdown: str) -> None:
    """The check numbers come from the tracker and skip 3, so they cannot carry a heading on their
    own — a reader without the tracker open learns nothing from `Check 4`."""
    assert "## Public surface with no caller outside its own module" in markdown
    assert "## Private names used across module boundaries" in markdown
    assert "## Intra-module call depth" in markdown
    assert "## Intra-folder import depth" in markdown
    assert "## Dead code" in markdown
    assert "## Check " not in markdown
    for number in (1, 2, 4, 5):
        assert f"*Cross-reference: Check {number}.*" in markdown
    assert "Why Check 3 is missing" in markdown, "the one gap must be explained in-report"


def test_report_names_the_functions_not_only_the_counts(markdown: str) -> None:
    """Counts alone are not actionable; the names are the worklist."""
    assert "`only_home`" in markdown
    assert "`is_dead`" in markdown
    assert "`rule` x4" in markdown


def test_report_carries_no_timestamp(markdown: str) -> None:
    """It is meant to be diffed between runs, which a timestamp would defeat on every line."""
    assert "diffed between runs" in markdown
    for row in markdown.splitlines():
        assert "202" not in row.replace("2026", ""), f"possible date in: {row}"


def test_html_is_self_contained_and_renders_the_tables(markdown: str) -> None:
    html = render_html(markdown, CONFIG)

    assert html.startswith("<!doctype html>")
    assert "<title>Carpet diagnostics — pkg</title>" in html
    assert "<style>" in html and "http" not in html, "no external stylesheet, font or script"
    # 5 payload tables, 5 column glossaries, the Method tool list, the bucket derivation.
    assert html.count("<table>") == 12
    assert "<td>" in html and "| module |" not in html, "markdown tables became real tables"
